"""Turns hits.json (from the screens prototype) into src/hits.h for the firmware."""
import json, sys
src = sys.argv[1]; out = sys.argv[2]
d = json.load(open(src))
names = [s['name'] for s in d['screens']]
idx = {n: i for i, n in enumerate(names)}
BACK, HOME, NONE = -2, -3, -1
def target(e):
    t, a = e['t'], e['a']
    if t == 'back': return BACK
    if t == 'none': return HOME if a == 'home' else NONE
    if t in idx: return idx[t]
    return NONE  # act:, mood:, theme:, app:, edit, ... are static in this first build
L = ['// generated by tools/make_hits.py, do not edit', '#pragma once', '#include <stdint.h>',
     'struct Hit { int16_t x, y, w, h; int16_t to; };',
     '#define S_NONE -1', '#define S_BACK -2', '#define S_HOME -3']
for n in names: L.append('#define SCR_%s %d' % (n.upper(), idx[n]))
L.append('#define SCR_COUNT %d' % len(names))
L.append('static const char* const SCR_NAMES[SCR_COUNT] = {%s};' % ','.join('"%s"' % n for n in names))
for i, s in enumerate(d['screens']):
    hs = [(e['x'], e['y'], e['w'], e['h'], target(e)) for e in s['hits'] if target(e) != NONE]
    L.append('static const Hit HITS_%d[] = {%s};' % (i, ','.join('{%d,%d,%d,%d,%d}' % tuple(round(v) for v in h) for h in hs) or '{0,0,0,0,S_NONE}'))
    L.append('#define NHITS_%d %d' % (i, len(hs)))
L.append('static const Hit* const HITS[SCR_COUNT] = {%s};' % ','.join('HITS_%d' % i for i in range(len(names))))
L.append('static const uint8_t NHITS[SCR_COUNT] = {%s};' % ','.join('NHITS_%d' % i for i in range(len(names))))
back = ','.join('%d' % (idx[d['backs'].get(n)] if d['backs'].get(n) in idx else -1) for n in names)
L.append('static const int8_t BACKS[SCR_COUNT] = {%s};' % back)
open(out, 'w').write('\n'.join(L) + '\n')
print(len(names), 'screens')
